import { test } from 'node:test';
import assert from 'node:assert/strict';

import { apiEntries, compareReports, removed } from './api-compat.mjs';

/** Wrap declarations in the shape of an api-extractor report. */
const report = (ts) =>
  `## API Report File for "x"\n\n> Do not edit this file.\n\n\`\`\`ts\n\n${ts}\n\n// (No @packageDocumentation comment for this package)\n\n\`\`\`\n`;

const release = report(`// @public
export interface Params {
    // (undocumented)
    country: string;
    idType?: string;
}

// @public (undocumented)
export const VERSION = "1.2.3";

// @public
export class Client {
    constructor(fields: {
        apiKey: string;
        timeout?: number;
    });
    verify(params: Params): Promise<void>;
}

// @public
export type Result = {
    kind: 'a';
    a: string;
} | {
    kind: 'b';
    b: number;
};
`);

test('an identical report has no breaks', () => {
  assert.deepEqual(compareReports(release, release), { introduced: [], inherited: [] });
});

test('a removed member is a break', () => {
  const head = release.replace('    idType?: string;\n', '');
  assert.deepEqual(compareReports(release, head).introduced, [
    'export interface Params :: idType?: string;',
  ]);
});

test('a changed member is a break', () => {
  const head = release.replace('idType?: string;', 'idType: string;');
  assert.deepEqual(compareReports(release, head).introduced, [
    'export interface Params :: idType?: string;',
  ]);
});

test('an added member is not a break', () => {
  const head = release.replace('    idType?: string;\n', '    idType?: string;\n    extra?: boolean;\n');
  assert.deepEqual(compareReports(release, head), { introduced: [], inherited: [] });
});

test('a removed export is a break', () => {
  const head = release.replace(/\/\/ @public\nexport class Client \{[\s\S]*?\n\}\n/, '');
  const { introduced } = compareReports(release, head);
  assert.ok(introduced.includes(' :: export class Client {'), introduced.join('\n'));
  assert.ok(
    introduced.includes('export class Client :: verify(params: Params): Promise<void>;'),
    introduced.join('\n'),
  );
});

test('a changed VERSION constant is not a break', () => {
  const head = release.replace('VERSION = "1.2.3"', 'VERSION = "2.0.0"');
  assert.deepEqual(compareReports(release, head), { introduced: [], inherited: [] });
  assert.ok(apiEntries(release).has(' :: export const VERSION: string;'));
});

test('members of a multi-line type are keyed by their enclosing declaration', () => {
  const entries = apiEntries(release);
  assert.ok(entries.has('export class Client > constructor(fields: :: apiKey: string;'));
  const head = release.replace('        timeout?: number;\n', '');
  assert.deepEqual(compareReports(release, head).introduced, [
    'export class Client > constructor(fields: :: timeout?: number;',
  ]);
  // The scope closes again: verify is still a direct member of Client.
  assert.ok(entries.has('export class Client :: verify(params: Params): Promise<void>;'));
});

test('a line that closes one scope and opens another keeps the nesting right', () => {
  const entries = apiEntries(release);
  assert.ok(entries.has('export type Result = } | :: b: number;'), [...entries].join('\n'));
  assert.ok(entries.has('export type Result = :: a: string;'));
  // Moving b into the first branch is a change to the union.
  const head = release.replace("    a: string;\n} | {\n    kind: 'b';\n    b: number;", "    a: string;\n    b: number;\n} | {\n    kind: 'b';");
  assert.ok(compareReports(release, head).introduced.includes('export type Result = } | :: b: number;'));
  // Nothing after the union is attributed to it.
  const trailing = report('export type T = {\n    x: 1;\n} | {\n    y: 2;\n};\nexport interface After {\n    z: 3;\n}');
  assert.ok(apiEntries(trailing).has('export interface After :: z: 3;'));
});

test('breaks the base branch already has are inherited, not introduced', () => {
  const base = release.replace('    idType?: string;\n', '');
  const head = base.replace('    country: string;\n', '');
  assert.deepEqual(compareReports(release, head, base), {
    introduced: ['export interface Params :: country: string;'],
    inherited: ['export interface Params :: idType?: string;'],
  });
  // A PR that changes nothing on top of the base introduces nothing.
  assert.deepEqual(compareReports(release, base, base).introduced, []);
});

test('removed lists entries missing from the second set, sorted', () => {
  assert.deepEqual(removed(new Set(['b', 'a', 'c']), new Set(['c'])), ['a', 'b']);
});

test('a file that is not a report is rejected', () => {
  assert.throws(() => apiEntries('no code block here'), /not an api-extractor report/);
});
